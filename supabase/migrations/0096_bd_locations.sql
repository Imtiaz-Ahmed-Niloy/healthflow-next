-- 0096_bd_locations.sql
-- Bangladesh's divisions, districts and upazilas, as tables that point at
-- each other: division >> district >> upazila.
--
-- Hospitals and chambers kept their division, district and subdistrict as
-- free text, and the site's pickers used a short list in src/data that only
-- knew a dozen districts' upazilas. Now the whole country is here, and the
-- Find Doctors filters read it.
--
-- The data: 8 divisions, 64 districts and 494 upazilas from
-- nuhil/bangladesh-geocode (read 2026-09-16), which carries the new ones
-- (Lalmai, Eidgaon, Dasar, Madhyanagar). Names are in the current official
-- spelling — Cumilla, Barishal, Bogura, Jashore, Cox's Bazar — and every
-- older or common spelling (Comilla, Barisal, Bogra, Jessore, Coxsbazar...)
-- is kept in `aliases`, so a search or a hospital's typed district finds it
-- either way. Bangla names are in `bn_name`.
--
-- Dhaka District's five upazilas (Savar, Dhamrai, Keraniganj, Nawabganj,
-- Dohar) leave out the city itself, so the 50 Dhaka Metropolitan Police
-- thanas (Gulshan, Dhanmondi, Mirpur...) sit beside them with kind 'thana'.
--
-- The three tables are global lookups: anyone may read them — the public
-- doctor and hospital search runs signed out — and only the super admin
-- writes.

create table public.bd_divisions (
  id         smallint generated by default as identity primary key,
  name       text not null
               constraint bd_divisions_name_check check (length(btrim(name)) between 1 and 100),
  bn_name    text,
  -- Other spellings: "Chittagong", "Barisal".
  aliases    text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.bd_districts (
  id          smallint generated by default as identity primary key,
  division_id smallint not null references public.bd_divisions (id) on delete restrict,
  name        text not null
                constraint bd_districts_name_check check (length(btrim(name)) between 1 and 100),
  bn_name     text,
  -- Other spellings: "Comilla", "Bogra", "Jessore".
  aliases     text[] not null default '{}',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table public.bd_upazilas (
  id          smallint generated by default as identity primary key,
  district_id smallint not null references public.bd_districts (id) on delete restrict,
  name        text not null
                constraint bd_upazilas_name_check check (length(btrim(name)) between 1 and 100),
  bn_name     text,
  aliases     text[] not null default '{}',
  -- 'thana' for a city's police-station areas (Dhaka's), 'upazila' otherwise.
  kind        text not null default 'upazila'
                constraint bd_upazilas_kind_check check (kind in ('upazila', 'thana')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create unique index bd_divisions_name_key on public.bd_divisions (lower(btrim(name)));
create unique index bd_districts_name_key on public.bd_districts (lower(btrim(name)));
create index bd_districts_division_idx on public.bd_districts (division_id);
-- Kaliganj, Lohagara, Nawabganj... repeat across districts, never within one.
create unique index bd_upazilas_name_key on public.bd_upazilas (district_id, lower(btrim(name)));
create index bd_upazilas_district_idx on public.bd_upazilas (district_id);

create trigger bd_divisions_set_updated_at before update on public.bd_divisions
  for each row execute function public.set_updated_at();
create trigger bd_districts_set_updated_at before update on public.bd_districts
  for each row execute function public.set_updated_at();
create trigger bd_upazilas_set_updated_at before update on public.bd_upazilas
  for each row execute function public.set_updated_at();

