   set district = btrim(split_part(t.location, ',', 1))
 where t.district is null
   and exists (select 1 from public.bd_districts d
                where public.bd_matches(split_part(t.location, ',', 1), d.name, d.bn_name, d.aliases));

-- A chamber at "Dhanmondi" in Dhaka: that part names the upazila or thana.
update public.tenants t
   set subdistrict = btrim(split_part(t.location, ',', 1))
 where t.subdistrict is null
   and exists (select 1 from public.bd_upazilas u
                where public.bd_matches(split_part(t.location, ',', 1), u.name, u.bn_name, u.aliases)
                  and (t.district is null
                       or u.district_id = (select d.id from public.bd_districts d where d.name = t.district)));

