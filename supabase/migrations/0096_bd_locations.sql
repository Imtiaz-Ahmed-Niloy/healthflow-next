create policy bd_divisions_select on public.bd_divisions for select to anon, authenticated using (true);
create policy bd_districts_select on public.bd_districts for select to anon, authenticated using (true);
create policy bd_upazilas_select on public.bd_upazilas for select to anon, authenticated using (true);

create policy bd_divisions_write on public.bd_divisions for all to authenticated
  using (public.is_super_admin()) with check (public.is_super_admin());
create policy bd_districts_write on public.bd_districts for all to authenticated
  using (public.is_super_admin()) with check (public.is_super_admin());
create policy bd_upazilas_write on public.bd_upazilas for all to authenticated
  using (public.is_super_admin()) with check (public.is_super_admin());

