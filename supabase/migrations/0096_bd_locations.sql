-- ------------------------------------------------------------- matching ---

-- "Cox's Bazar", "Coxs Bazar" and "coxsbazar" are one place: lower case,
-- nothing but letters and digits.
create function public.bd_norm(p text)
returns text
language sql
immutable
set search_path = ''
as $$
  select nullif(lower(regexp_replace(coalesce(p, ''), '[^[:alnum:]]+', '', 'g')), '')
$$;

-- Does typed text name this place — by its name, its Bangla name, or any alias?
create function public.bd_matches(p text, p_name text, p_bn_name text, p_aliases text[])
returns boolean
language sql
immutable
set search_path = ''
as $$
  select public.bd_norm(p) is not null and (
    public.bd_norm(p) = public.bd_norm(p_name)
    or public.bd_norm(p) = public.bd_norm(p_bn_name)
    or exists (select 1 from unnest(p_aliases) a where public.bd_norm(a) = public.bd_norm(p))
  )
$$;

-- --------------------------------------------------------------- tenants ---
-- A hospital's or chamber's division, district and subdistrict stay text —
-- every form and the doctors_public view read them as text — but they are
-- written in the tables' spelling. "Comilla" is saved as "Cumilla"; a known
-- district fills in its division; an upazila found in only one district
-- fills in both. Text that matches nothing is kept as typed.

create function public.tenants_bd_canonical()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_division public.bd_divisions%rowtype;
  v_district public.bd_districts%rowtype;
  v_upazila  public.bd_upazilas%rowtype;
begin
  if new.district is not null then
    select * into v_district from public.bd_districts d
     where public.bd_matches(new.district, d.name, d.bn_name, d.aliases)
     limit 1;
  end if;

  if new.subdistrict is not null then
    if v_district.id is not null then
      select * into v_upazila from public.bd_upazilas u
       where u.district_id = v_district.id
         and public.bd_matches(new.subdistrict, u.name, u.bn_name, u.aliases)
       limit 1;
    elsif new.district is null then
      select * into v_upazila from public.bd_upazilas u
       where public.bd_matches(new.subdistrict, u.name, u.bn_name, u.aliases)
         and (select count(*) from public.bd_upazilas x
               where public.bd_matches(new.subdistrict, x.name, x.bn_name, x.aliases)) = 1;
      if v_upazila.id is not null then
        select * into v_district from public.bd_districts where id = v_upazila.district_id;
      end if;
    end if;
  end if;

  if v_district.id is not null then
    new.district := v_district.name;
    select * into v_division from public.bd_divisions where id = v_district.division_id;
    new.division := v_division.name;
  elsif new.division is not null then
    select * into v_division from public.bd_divisions dv
     where public.bd_matches(new.division, dv.name, dv.bn_name, dv.aliases)
     limit 1;
    if v_division.id is not null then
      new.division := v_division.name;
    end if;
  end if;

  if v_upazila.id is not null then
    new.subdistrict := v_upazila.name;
  end if;

  return new;
end
$$;

create trigger tenants_bd_canonical
  before insert or update of division, district, subdistrict on public.tenants
  for each row execute function public.tenants_bd_canonical();

